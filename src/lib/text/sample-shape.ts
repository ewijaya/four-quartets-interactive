/**
 * The *shape* of the sequence — stanza line counts per movement — used to generate
 * placeholder text. Counts are approximations of the printed poem (the real text is
 * never stored here); they only need to be realistic enough to exercise layout,
 * navigation, scenes and visualizations.
 *
 * Each stanza entry is a line count, optionally with decorations:
 *   { n: 15, indent: [[3, 8]] }  → lines 3 and 8 of the stanza indented 8 spaces
 *   { n: 12, step: [5] }         → line 5 of the stanza is a stepped (dropped) line
 */
import type { QuartetId } from "../model";

export interface StanzaShape {
  n: number;
  indent?: Array<[line: number, spaces: number]>;
  step?: number[];
}
export type MovementShape = StanzaShape[];

export interface QuartetShape {
  id: QuartetId;
  code: string;
  title: string;
  /** Front matter placeholder lines, blank-line separated paragraphs. */
  front: string[][];
  movements: [MovementShape, MovementShape, MovementShape, MovementShape, MovementShape];
}

const s = (n: number, extra: Omit<StanzaShape, "n"> = {}): StanzaShape => ({ n, ...extra });

