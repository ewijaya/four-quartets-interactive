const ROMAN = ["I", "II", "III", "IV", "V"];

/** Render a shape as a plain-text source file in the importer's input format. */
export function renderSampleSource(q: QuartetShape): string {
  const out: string[] = [
    "%% still-point sample text — placeholder lines only, generated by scripts/make-sample.ts",
    "%% edition: sample (shape approximates the printed sequence)",
    q.title,
    "",
  ];
  for (const para of q.front) {
    out.push(...para, "");
  }
  q.movements.forEach((mv, mi) => {
    out.push(ROMAN[mi]!, "");
    let n = 0;
    mv.forEach((st) => {
      for (let i = 1; i <= st.n; i++) {
        n++;
        const text = `${q.code}.${mi + 1} line ${n} — placeholder`;
        const ind = st.indent?.find(([l]) => l === i)?.[1] ?? 0;
        if (st.step?.includes(i)) {
          out.push("%% step", " ".repeat(24) + text);
        } else {
          out.push(" ".repeat(ind) + text);
        }
      }
      out.push("");
    });
  });
  return out.join("\n");
}
